// ─────────────────────────────────────────────────────────────
//  لیست کارمندان ربات
//  آیدی عددی تلگرام هر کارمند را داخل آرایه زیر بنویس (با کاما جدا کن)
//  مثال:  const STAFF_IDS = [123456789, 987654321];
// ─────────────────────────────────────────────────────────────
const STAFF_IDS = [
  8104311231, 1380876907, 1319965488, 
];

const STAFF_SET = new Set(STAFF_IDS.map(Number));

export function isStaff(userId) {
  return STAFF_SET.has(Number(userId));
}
